# Faça um programa que receba um número de usuário e exiba este número, apenas se for par.

numero = int(input("Digite o número:"))

 
if numero % 2 == 0: # Comando Mod: Se o RESTO do Número dividido por 2 "for igual a ZERO"
    print()
    print(f"Seu número é: {numero}")
    print()

else :
    print()
    print("Não podemos exibir o número")
    print()