
# decisão/condicional - "==" é um operador de comparação

# Operadores de comparação
# ==   - igual a
# >   - maior que
# <   - menor que 
# >=   - maior ou igual a
# <=   - menor ou igual a
# !=   - diferente de 


x = 5

if x == 5 : # Uma condição, se x for igual a 5...
    print()
    print("x é igual a 5") # sempre apertar um "TAB", só faz parte do if se tiver "TABULAÇÂO" - na linguagem python

    print("Fim do programa")
    print()

else : # Se não...
    print()
    print("X é != (diferente) de 5")

    print("Fim do programa")
    print()