# Faça um programa que receba um número do usuário e informe se este número é par ou ímpar.

numero = int(input("Digite o número:"))

 
if numero % 2 == 0: # Comando Mod: Se o RESTO do Número dividido por 2 "for igual a ZERO"
    print()
    print("Número par")
    print()

else :
    print()
    print("Número ímpar")
    print()